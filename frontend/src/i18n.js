function fill(s, vars) {
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m)) : s;
}

export function translate(lang, key, vars) {
  if (key === null || key === undefined) return "";
  key = String(key);
  const i = IDX[lang];
  if (i === undefined) return fill(key, vars);
  const hit = DICT[key];
  if (hit) return fill(hit[i], vars);
  const tr = (k) => translate(lang, k);
  for (const p of PATTERNS) {
    const m = p[0].exec(key);
    if (m) {
      const tpl = p[1 + i];
      return typeof tpl === "function" ? tpl(m, tr) : tpl.replace(/\$(\d)/g, (_, n) => m[Number(n)] ?? "");
    }
  }
  return fill(key, vars);
}

/** t("English text", { vars }, langOverride) */
export function useT() {
  const { lang } = useLang();
  return (key, vars, override) => translate(override || lang, key, vars);
}
